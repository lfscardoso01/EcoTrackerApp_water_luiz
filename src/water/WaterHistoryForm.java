    private void generateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_generateButtonActionPerformed
        // TODO add your handling code here:
       try {
        // Reads the report dates.
        String startDate = textLb1.getText().trim();
        String endDate = textLb2.getText().trim();

        if (startDate.isEmpty() || endDate.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Enter the start and end dates.");
            return;
        }

        // Generates and displays the report.
        String report = WaterActivityForm.getManager()
                .generateReport(startDate, endDate);

        jTextArea1.setText(report);

    } catch (java.time.format.DateTimeParseException ex) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Check the report dates and recorded activity dates. "
                        + "Use valid dates in DD-MM-YYYY format.");

    } catch (IllegalArgumentException ex) {
        javax.swing.JOptionPane.showMessageDialog(
                this, ex.getMessage());
    }
    }//GEN-LAST:event_generateButtonActionPerformed

    private void searchButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchButtonActionPerformed
        // TODO add your handling code here:
            try {
        // Reads the ID entered by the user.
        int id = Integer.parseInt(searchText.getText().trim());

        // Searches the shared list.
        WaterActivity activity =
                WaterActivityForm.getManager().searchActivity(id);

        if (activity != null) {
            jTextArea1.setText(activity.displayInfo());
        } else {
            jTextArea1.setText("Record not found.");
        }

    } catch (NumberFormatException ex) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Enter a valid record ID.");
    }
    }//GEN-LAST:event_searchButtonActionPerformed


